-- ---------------------------------------------------------------------
--  แบบ A — ล้างข้อมูล แต่เก็บโครงสร้างและบัญชีเจ้าหน้าที่ไว้
-- ---------------------------------------------------------------------
--  ใช้เมื่อ: อยากส่งต่อระบบที่พร้อมใช้ทันที เจ้าหน้าที่ล็อกอินได้เลย
--  ลบ: ผู้ยืม ประวัติยืม-คืน คำขอ audit log การปรับสต็อก
--  เก็บ: ตาราง บัญชีผู้ใช้ รายการอุปกรณ์ (แต่จำนวนคงเหลือถูกรีเซ็ตให้เต็ม)
--
--  ลบพาสคีย์ด้วย เพราะพาสคีย์ผูกกับโดเมน — ถ้าเพื่อนใช้โดเมนใหม่
--  พาสคีย์เดิมใช้ไม่ได้อยู่แล้ว และถ้าไม่ลบ จะไม่มีใครล็อกอินได้เลย
--  (บัญชีที่มีพาสคีย์ ระบบไม่ให้ใช้รหัสผ่าน) — อ่าน HANDOVER.md ประกอบ

BEGIN;

TRUNCATE TABLE
  audit_log,
  stock_adjustments,
  records,
  requests,
  borrowers,
  passkeys,
  webauthn_challenges,
  rate_limits
RESTART IDENTITY CASCADE;

-- TRUNCATE ... RESTART IDENTITY รีเซ็ตเฉพาะ identity column
-- ส่วนรหัสอ่านง่าย (B0001, R0001) มาจาก sequence แยก ต้องสั่งเอง
-- ไม่งั้นผู้ยืมคนแรกของเพื่อนจะได้รหัส B0247 ต่อจากของเก่า
ALTER SEQUENCE borrower_seq   RESTART WITH 1;
ALTER SEQUENCE record_seq     RESTART WITH 1;
ALTER SEQUENCE request_seq    RESTART WITH 1;
ALTER SEQUENCE audit_seq      RESTART WITH 1;
ALTER SEQUENCE adjustment_seq RESTART WITH 1;
ALTER SEQUENCE passkey_seq    RESTART WITH 1;

-- อุปกรณ์ที่ถูกยืมอยู่ตอนล้าง ต้องคืนยอดให้เต็ม ไม่งั้นสต็อกจะขาดค้างไว้
-- โดยไม่มีรายการยืมที่อธิบายว่าของหายไปไหน
UPDATE equipment SET available_qty = total_qty;

-- ทุกคนต้องล็อกอินใหม่ และรหัสผ่านกลับมาใช้ได้อีกครั้ง (เพราะพาสคีย์ถูกลบไปแล้ว)
UPDATE users SET session_version = session_version + 1;

COMMIT;

-- ตรวจผล — ควรได้ 0 ทั้งหมด ยกเว้นผู้ใช้กับอุปกรณ์
SELECT
  (SELECT count(*) FROM borrowers)         AS "ผู้ยืม",
  (SELECT count(*) FROM records)           AS "รายการยืม",
  (SELECT count(*) FROM requests)          AS "คำขอ",
  (SELECT count(*) FROM audit_log)         AS "audit",
  (SELECT count(*) FROM passkeys)          AS "พาสคีย์",
  (SELECT count(*) FROM users)             AS "เจ้าหน้าที่_เหลือไว้",
  (SELECT count(*) FROM equipment)         AS "อุปกรณ์_เหลือไว้";


